$root = "D:\code\Poracode-master\src\renderer\locales"
foreach ($lang in $langs) {
  $path = Join-Path $root "$lang\messages.po"
  $text = [System.IO.File]::ReadAllText($path)
  $map = $T[$lang]
  $count = 0
  foreach ($msgid in $map.Keys) {
    # Match a msgid block followed by an empty msgstr.
    $pattern = [regex]::Escape("msgid `"$msgid`"") + "`r?`nmsgstr `"`""
    $replacement = "msgid `"$msgid`"`r`nmsgstr `"" + $map[$msgid] + "`""
    $newText = [regex]::Replace($text, $pattern, $replacement)
    if ($newText -ne $text) { $count++ }
    $text = $newText
  }
  [System.IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false))
  Write-Output "$lang filled=$count"
}
